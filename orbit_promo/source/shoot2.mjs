import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const out=process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport:{width:1500,height:860}, deviceScaleFactor:2 });
await p.route(u=>!u.href.startsWith('http://localhost'), r=>r.abort());
p.on('pageerror', e=>console.log('ERR',e.message));
await p.goto('http://localhost:8765/tool/index.html', {waitUntil:'load'});
await p.waitForTimeout(1200);
const W=ms=>p.waitForTimeout(ms);
const full=async n=>{await W(1400); await p.evaluate(()=>window.scrollTo(0,0)); await p.screenshot({path:`${out}/${n}.png`}); console.log(n);};
const card=async n=>{await W(2600); await p.locator('.chart-card').screenshot({path:`${out}/${n}.png`}); console.log(n);};
const chip=(sel,val)=>p.evaluate(([s,v])=>{const el=document.querySelector(`${s} .chip[data-value="${v}"]`); el.click();},[sel,val]);
const setSel=(id,txt)=>p.evaluate(([id,t])=>{const e=document.getElementById(id); const o=[...e.options].find(o=>o.text===t); e.value=o.value; e.dispatchEvent(new Event('change'));},[id,txt]);
const tog=(id,on=true)=>p.evaluate(([id,on])=>{const e=document.getElementById(id); if(e.checked!==on){e.checked=on; e.dispatchEvent(new Event('change'));}},[id,on]);
await full('00_empty');
await p.evaluate(()=>loadSample('city')); await full('01_pasted');
await p.evaluate(()=>analyzeData()); await W(500);
await p.addStyleTag({content:'.toast,#toastHost,.toasts{display:none!important} .plot-host .empty{display:none!important} .topbar{position:relative!important}'});
await card('02_bar');
await p.evaluate(()=>setChartMode('pie')); await card('03_pie');
await p.evaluate(()=>setChartMode('scatter'));
await setSel('colorCol','Region'); await card('04_scatter'); await full('04_scatter_full');
await tog('showLabels',true); await card('05_labels');
await setSel('yCol','CO2_Mt'); await setSel('sizeCol','Population_M');
await chip('#regChips','linear'); await chip('#bandChips','both'); await card('06_regression');
await tog('showMean',true); await card('07_quadrant'); await full('07_quadrant_full');
await p.evaluate(()=>{setChartMode('other');setSubMode('box');}); await setSel('boxGroupCol','Region'); await setSel('boxValueCol','CO2_Mt'); await tog('boxPoints',true); await card('08_box');
await p.evaluate(()=>setSubMode('treemap')); await card('09_treemap');
await p.evaluate(()=>setSubMode('histogram')); await card('10_hist');
await p.evaluate(()=>setSubMode('pareto')); await card('11_pareto');
await b.close();
